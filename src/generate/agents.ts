import { join } from 'node:path';
import { AGENT_NAMES, AGENT_TARGETS, type AgentName } from './targets.js';
import { typeAlias } from '../core/profile.js';
import { UserError, readIfExists, writeWithStatus } from '../core/util.js';
import type { AgentFileResult, Profile } from '../core/types.js';

// Files generated for the coding agents (SPEC.md section 10; paths per agent in targets.ts):
//  - a marked block in the instructions file the agent always loads
//  - three agent skills (open standard: agentskills.io)
// They belong to okfcli: running `okfcli init` again regenerates them.

export const BLOCK_START = '<!-- okfcli:start -->';
export const BLOCK_END = '<!-- okfcli:end -->';

export function pointerBlock(wiki: string): string {
  return [
    BLOCK_START,
    '## Project wiki',
    '',
    `This project keeps its knowledge (architecture, patterns, conventions, workflows, testing) in an OKF wiki at \`${wiki}/\`.`,
    '',
    `- Before changing code, read \`${wiki}/index.md\` and the pages relevant to the task (skill \`okf-consult-wiki\`).`,
    '- When a change affects documented rules, patterns or conventions, update the wiki (skill `okf-update-wiki`). Use the `okfcli` CLI to create pages; never edit `index.md` files by hand or write `verified` entries.',
    '- Never mark a page as reviewed on your own: only a person reviews pages (skill `okf-review-wiki`).',
    BLOCK_END,
    '',
  ].join('\n');
}

const skill = (name: string, description: string, body: string, version: string): string =>
  `---\nname: ${name}\ndescription: ${description}\n---\n<!-- Generated by okfcli ${version}. Regenerated by "okfcli init": do not edit. -->\n\n${body.trim()}\n`;

function typeList(profile: Profile): string {
  return profile.folders.map((f) => `   - \`${typeAlias(f.type)}\` -> \`${f.name}/\` (sections: ${f.sections.map((s) => `\`# ${s}\``).join(', ') || 'none'})`).join('\n');
}

export function skillFiles({ wiki, profile, version }: { wiki: string; profile: Profile; version: string }): { path: string; text: string }[] {
  // Quoted only when needed, so paths with spaces still work in the commands agents run.
  const wikiArg = /^[\w./@+-]+$/.test(wiki) ? wiki : JSON.stringify(wiki);
  const consult = skill(
    'okf-consult-wiki',
    'Find project knowledge in the wiki before writing or changing code: architecture, patterns, conventions, workflows and testing rules. Use at the start of any task that touches the codebase.',
    `
# Consult the project wiki

The wiki lives in \`${wiki}/\`. Read only what the task needs.

1. Read \`${wiki}/index.md\`. It lists the folders this wiki has, each with a description; the folders differ from one wiki to another, so do not assume any.
2. Open the \`index.md\` of the folders that matter for the task, then the pages it points to.
3. For "how do I do X" questions look for a workflow first: workflows link to the patterns they rely on. Rules and structure are usually under architecture and conventions, and how to run and write tests under testing, when the wiki has those folders.
4. Follow what the pages say. If the wiki is silent or contradicts the code, say so instead of guessing, and propose a wiki update (skill \`okf-update-wiki\`).
5. A page without a \`verified\` entry has not been reviewed by a person: use it, but flag the uncertainty when the answer depends on it.
`,
    version,
  );

  const update = skill(
    'okf-update-wiki',
    'Update the project wiki after a change affects documented knowledge, or document something new. Uses the okfcli CLI so structure and indexes stay correct.',
    `
# Update the project wiki

The wiki lives in \`${wiki}/\`. The \`okfcli\` CLI does the mechanical work; you only write content.

1. Check whether the change touches knowledge that is already documented. If so, **edit that page in place**. Do not create a duplicate, and do not add a page that only records a decision: put the reason in the page's \`# Why\` section.
2. For new knowledge, create the page with the CLI, not by hand:

   \`okfcli new <type> <name> --description "<one sentence>" --wiki ${wikiArg}\`

   It creates the file with its frontmatter and required sections, and registers it in the folder index. Types:

${typeList(profile)}

   \`<name>\` is kebab-case and relative to the folder (for example \`state-management\` or \`ui/forms\`).
3. Fill in every section and delete the \`<!-- TODO -->\` comments. Write in the language the existing pages use.
4. Never edit \`index.md\` files and never write \`verified\` entries: you are not a reviewer. New and edited pages stay unreviewed until a person verifies them.
5. If something no longer applies, set \`status: deprecated\` in that page's frontmatter instead of deleting it.
6. Run \`okfcli validate --fix --wiki ${wikiArg}\`, then fix whatever it still reports (it names the file, the rule and how to fix it).
`,
    version,
  );

  const review = skill(
    'okf-review-wiki',
    'Walk a person through the wiki pages nobody has reviewed yet and record their review. Use when asked to review, verify or sign off wiki pages.',
    `
# Review wiki pages with a person

Reviewing is a human act. You prepare the review; the person decides.

1. Run \`okfcli validate --json --wiki ${wikiArg}\`. The pages to review are the issues with rule \`frontmatter.verified\` (never reviewed) or \`frontmatter.verified-outdated\` (changed after being verified). The \`review\` field has the totals.
2. Pick one page at a time (ask the person where to start if there are many). Summarise it, check it against the code, and point out anything that looks wrong or missing. Fix problems with the person's agreement.
3. A page with unfilled \`<!-- TODO -->\` comments is not ready: complete it first.
4. Ask the person explicitly whether they confirm the page. Only after a clear yes, run:

   \`okfcli verify <path> --by human:<id> --wiki ${wikiArg}\`

   where \`<id>\` identifies that person (ask if you do not know it).
5. Never use a \`human:\` actor for yourself, never verify a page the person has not confirmed, and never write \`verified\` entries by hand.
6. If the person does not confirm a page, leave it as it is and move on.
7. Finish with \`okfcli validate --wiki ${wikiArg}\` and report how many pages are still unreviewed.
`,
    version,
  );

  return [
    { path: 'okf-consult-wiki/SKILL.md', text: consult },
    { path: 'okf-update-wiki/SKILL.md', text: update },
    { path: 'okf-review-wiki/SKILL.md', text: review },
  ];
}

// Inserts the block into the file text, or replaces it if the markers are already there.
export function upsertBlock(current: string | null, block: string, file: string): string {
  if (current === null) return block;
  const start = current.indexOf(BLOCK_START);
  if (start === -1) return `${current.replace(/\s+$/, '')}${current.trim() ? '\n\n' : ''}${block}`;
  const end = current.indexOf(BLOCK_END, start);
  if (end === -1) {
    throw new UserError(`${file} has "${BLOCK_START}" without "${BLOCK_END}". Fix or remove the marker, then run "okfcli init" again.`);
  }
  return current.slice(0, start) + block.trimEnd() + current.slice(end + BLOCK_END.length);
}

// Which of the candidate files carries the pointer block: the one that already
// has it, else the first that exists, else the first candidate (created).
export function pointerFile(projectRoot: string, candidates: readonly [string, ...string[]]): string {
  const withBlock = candidates.find((f) => readIfExists(join(projectRoot, f))?.includes(BLOCK_START));
  return withBlock ?? candidates.find((f) => readIfExists(join(projectRoot, f)) !== null) ?? candidates[0];
}

interface WriteAgentFilesOptions {
  projectRoot: string;
  wiki: string;
  profile: Profile;
  version: string;
  agents: AgentName[];
}

// Writes (or refreshes) the agent files of the chosen agents. Agents that share
// a destination (several read AGENTS.md or .agents/skills) write it only once.
export function writeAgentFiles({ projectRoot, wiki, profile, version, agents }: WriteAgentFilesOptions): AgentFileResult[] {
  // Fixed order (not the caller's), so the result never depends on how the flags were typed.
  const targets = AGENT_NAMES.filter((a) => agents.includes(a)).map((a) => AGENT_TARGETS[a]);
  const abs = (rel: string): string => join(projectRoot, rel);

  const files = new Map<string, string>();
  for (const { instructions } of targets) {
    const path = pointerFile(projectRoot, instructions);
    if (files.has(path)) continue;
    let current = readIfExists(abs(path));
    // A new CLAUDE.md hides AGENTS.md from Claude Code, so it imports it.
    if (current === null && instructions[0] === 'CLAUDE.md' && (files.has('AGENTS.md') || readIfExists(abs('AGENTS.md')) !== null)) {
      current = '@AGENTS.md\n';
    }
    files.set(path, upsertBlock(current, pointerBlock(wiki), path));
  }
  for (const dir of new Set(targets.map((t) => t.skillsDir))) {
    for (const skill of skillFiles({ wiki, profile, version })) files.set(`${dir}/${skill.path}`, skill.text);
  }
  return [...files].map(([path, text]) => ({ path, status: writeWithStatus(abs(path), text) }));
}
